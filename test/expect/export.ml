(* @mdexp

# Export

`central export <repo> -m MSG` moves changes made directly in `central`,
under `repo/<repo>/`, out into `<repo>`'s own standalone git repository - as
a single new commit on top of its `subrepo` branch.

It is the native-OCaml replacement for the one `git subrepo` command that
sits on `central`'s critical, day-to-day path: `git subrepo push`. Unlike
that command, `export` always squashes whatever changed since the last sync
into exactly one new commit, using the message supplied with `-m`.

Concretely, it:

1. Verifies the subrepo's `subrepo` branch has not moved since the last sync
   recorded in `repo/<repo>/.gitrepo` (if it has, someone likely pushed there
   directly - bring that in first before exporting).
2. Computes the diff of everything under `repo/<repo>/` since that sync,
   using `git diff --relative=`, which also strips the `repo/<repo>/` path
   prefix from the patch.
3. Applies that patch as one commit onto the subrepo's `subrepo` branch, via
   `git apply --3way --index`.
4. Updates `.gitrepo` in `central` to record the new sync point.

## A fake repo to work with

This walkthrough uses `Central_test_helpers` to build a fake `central`
repo with a made-up subrepo, `widget`, and a fake standalone repo standing
in for `widget`'s own history, wired together with a `.gitrepo` file
exactly as `central subrepo init` would leave them.

Right after that, `repo/widget/README.md` in `central` and `widget`'s own
`README.md` are identical: *)

let%expect_test "before" =
  let vcs = Volgo_git_unix.create () in
  let widget = Central.Subrepo.v "widget" in
  let fake_central = Central_test_helpers.create ~vcs ~subrepos:[ widget ] in
  let { Central_test_helpers.Fake_central.central_root; _ } = fake_central in
  Central_test_helpers.print_file
    ~repo_root:central_root
    ~path_in_repo:(Vcs.Path_in_repo.v "repo/widget/README.md");
  (* @mdexp.snapshot { lang: "markdown" } *)
  [%expect
    {|
    # widget

    This is a fake [widget] repo, generated by [Central_test_helpers] for tests.
    |}]
;;

(* @mdexp

## Editing directly in central, then exporting

Suppose someone edits `repo/widget/README.md` directly from within `central`
and commits it there - the way most day-to-day changes happen. Running
`export` then brings that change out, as a single new commit on top of
`widget`'s `subrepo` branch: *)

let%expect_test "edit and export" =
  let vcs = Volgo_git_unix.create () in
  let widget = Central.Subrepo.v "widget" in
  let fake_central = Central_test_helpers.create ~vcs ~subrepos:[ widget ] in
  let { Central_test_helpers.Fake_central.central_root; _ } = fake_central in
  let fake_widget =
    Central_test_helpers.Fake_central.find_exn fake_central ~subrepo:widget
  in
  let readme_path = Vcs.Path_in_repo.v "repo/widget/README.md" in
  Central_test_helpers.append_file
    ~repo_root:central_root
    ~path_in_repo:readme_path
    ~text:"\nAdded a line about installation.\n";
  Vcs.add vcs ~repo_root:central_root ~path:readme_path;
  let (_ : Vcs.Rev.t) =
    Central_test_helpers.commit
      ~vcs
      ~repo_root:central_root
      ~commit_message:"Document installation in widget's README"
  in
  let harness = Central_test_harness.create ~repo_root:central_root in
  let@ central = Central_test_harness.with_cli harness ~cwd:central_root in
  central [ [ "export"; "widget" ]; [ "-m"; "Document installation" ] ];
  (* @mdexp.snapshot *)
  [%expect
    {|
    $ central export widget -m "Document installation"
    ==================== widget ====================
    [ OK ] Applied patch in the subrepo.
    [ OK ] Exported to [widget].
    |}];
  (* @mdexp

     It landed in `widget`'s own history as one new commit on the `subrepo`
     branch, carrying exactly that change: *)
  Central_test_helpers.print_log_subjects
    ~vcs
    ~repo_root:fake_widget.repo_root
    ~ref_:"subrepo"
    ();
  (* @mdexp.snapshot *)
  [%expect
    {|
    Document installation
    Initial commit
    |}];
  Central_test_helpers.print_file
    ~repo_root:fake_widget.repo_root
    ~path_in_repo:(Vcs.Path_in_repo.v "README.md");
  (* @mdexp.snapshot { lang: "markdown" } *)
  [%expect
    {|
    # widget

    This is a fake [widget] repo, generated by [Central_test_helpers] for tests.

    Added a line about installation.
    |}]
;;

