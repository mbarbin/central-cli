(* @mdexp

## Exporting several subrepos at once

Chores that make the same systematic change across many subrepos are common
enough that `export` accepts more than one `REPO` at a time (or `--all` for
every subrepo it knows about) - each is exported in turn, in the order
given, with a separator banner between them, reusing the same `-m` message
for every commit: *)

let%expect_test "export several subrepos at once" =
  let vcs = Volgo_git_unix.create () in
  let widget = Central.Subrepo.v "widget" in
  let gadget = Central.Subrepo.v "gadget" in
  let fake_central = Central_test_helpers.create ~vcs ~subrepos:[ widget; gadget ] in
  let { Central_test_helpers.Fake_central.central_root; _ } = fake_central in
  let fake_widget =
    Central_test_helpers.Fake_central.find_exn fake_central ~subrepo:widget
  in
  let fake_gadget =
    Central_test_helpers.Fake_central.find_exn fake_central ~subrepo:gadget
  in
  List.iter [ widget; gadget ] ~f:(fun subrepo ->
    let path_in_repo =
      Vcs.Path_in_repo.v
        (Printf.sprintf "repo/%s/README.md" (Central.Subrepo.to_string subrepo))
    in
    Central_test_helpers.append_file
      ~repo_root:central_root
      ~path_in_repo
      ~text:"\nSee LICENSE for details.\n";
    Vcs.add vcs ~repo_root:central_root ~path:path_in_repo);
  let (_ : Vcs.Rev.t) =
    Central_test_helpers.commit
      ~vcs
      ~repo_root:central_root
      ~commit_message:"Add license footer to every subrepo"
  in
  let harness = Central_test_harness.create ~repo_root:central_root in
  let@ central = Central_test_harness.with_cli harness ~cwd:central_root in
  central [ [ "export"; "widget"; "gadget" ]; [ "-m"; "Add license footer" ] ];
  (* @mdexp.snapshot *)
  [%expect
    {|
    $ central export widget gadget -m "Add license footer"
    ==================== widget ====================
    [ OK ] Applied patch in the subrepo.
    [ OK ] Exported to [widget].
    ==================== gadget ====================
    [ OK ] Applied patch in the subrepo.
    [ OK ] Exported to [gadget].
    |}];
  (* @mdexp Both landed the same commit message on their own `subrepo` branch: *)
  List.iter
    [ fake_widget; fake_gadget ]
    ~f:(fun (fake_subrepo : Central_test_helpers.Fake_subrepo.t) ->
      Printf.printf "-- %s --\n" (Central.Subrepo.to_string fake_subrepo.subrepo);
      Central_test_helpers.print_log_subjects
        ~vcs
        ~repo_root:fake_subrepo.repo_root
        ~ref_:"subrepo"
        ();
      print_newline ());
  (* @mdexp.snapshot *)
  [%expect
    {|
    -- widget --
    Add license footer
    Initial commit
    -- gadget --
    Add license footer
    Initial commit
    |}];
  (* @mdexp

     `central todo` picks up both subrepos as done - since `export` doesn't
     touch `central`'s own history, both are shown ready for their next
     step, `advance-main`, while `central` itself needs a `push` for the
     `.gitrepo` updates: *)
  central [ [ "todo" ] ];
  (* @mdexp.snapshot *)
  [%expect
    {|
    $ central todo
    ┌──────────┬──────────────┬──────┐
    │ Repo     │ Next step    │ Diff │
    ├──────────┼──────────────┼──────┤
    │ central  │ push         │   12 │
    │   gadget │ advance-main │      │
    │   widget │ advance-main │      │
    └──────────┴──────────────┴──────┘
    |}]
;;

(* @mdexp

`export` stops at the first repo that fails, leaving the ones after it in
the list untouched - it doesn't try to skip ahead and report a summary at
the end. Say `gadget`'s `subrepo` branch moved independently in the
meantime (someone pushed to it directly, bypassing central) while `widget`
is perfectly exportable: *)

let%expect_test "stops at the first repo that fails" =
  let vcs = Volgo_git_unix.create () in
  let widget = Central.Subrepo.v "widget" in
  let gadget = Central.Subrepo.v "gadget" in
  let fake_central = Central_test_helpers.create ~vcs ~subrepos:[ widget; gadget ] in
  let { Central_test_helpers.Fake_central.central_root; _ } = fake_central in
  let fake_gadget =
    Central_test_helpers.Fake_central.find_exn fake_central ~subrepo:gadget
  in
  let widget_readme = Vcs.Path_in_repo.v "repo/widget/README.md" in
  Central_test_helpers.append_file
    ~repo_root:central_root
    ~path_in_repo:widget_readme
    ~text:"\nSee LICENSE for details.\n";
  Vcs.add vcs ~repo_root:central_root ~path:widget_readme;
  let (_ : Vcs.Rev.t) =
    Central_test_helpers.commit
      ~vcs
      ~repo_root:central_root
      ~commit_message:"Add license footer to widget"
  in
  (* [gadget]'s own history moved on its own, bypassing central entirely. *)
  let readme = Vcs.Path_in_repo.v "README.md" in
  Vcs.git
    vcs
    ~repo_root:fake_gadget.repo_root
    ~args:[ "checkout"; "subrepo" ]
    ~f:Vcs.Git.exit0;
  Central_test_helpers.append_file
    ~repo_root:fake_gadget.repo_root
    ~path_in_repo:readme
    ~text:"\nEdited directly upstream.\n";
  Vcs.add vcs ~repo_root:fake_gadget.repo_root ~path:readme;
  let (_ : Vcs.Rev.t) =
    Central_test_helpers.commit
      ~vcs
      ~repo_root:fake_gadget.repo_root
      ~commit_message:"Edited directly upstream"
  in
  let harness = Central_test_harness.create ~repo_root:central_root in
  let@ central = Central_test_harness.with_cli harness ~cwd:central_root in
  central [ [ "export"; "widget"; "gadget" ]; [ "-m"; "Add license footer" ] ];
  (* @mdexp.snapshot *)
  [%expect
    {|
    $ central export widget gadget -m "Add license footer"
    ==================== widget ====================
    [ OK ] Applied patch in the subrepo.
    [ OK ] Exported to [widget].
    ==================== gadget ====================
    Error: The [subrepo] branch of [gadget] has moved since the last sync
    recorded in [.gitrepo].
    Hint: Bring those changes into central first with [central import] before
    exporting, or pass [--force] to export anyway.
    [123]
    |}]
;;
