# Import

`central import <repo>` brings commits from the tip of the subrepo's
`subrepo` branch - normally landed there by fetching from the subrepo's real
remote - into `repo/REPO`. `-m MSG` is optional and defaults to `"Import
changes from REPO"`.

Unlike `export`, this has to account for central having moved on since the
last sync - so it picks between two ways of bringing the change in,
depending on whether central has any local changes of its own under
`repo/REPO`:

- If central hasn't touched `repo/REPO` at all since the last sync,
  `repo/REPO` at central's current HEAD is - by construction - exactly what
  it was at the last sync point, so the subrepo's diff is guaranteed to
  apply there too. There is nothing to merge, so `import` doesn't build
  one: it applies the diff directly as a single new commit on top of HEAD.
  This is the default, and it keeps history linear in the common case where
  central had no reason to conflict with what the subrepo brings in.
- Otherwise - central *does* have local changes of its own under
  `repo/REPO` - `import` falls back to an ordinary two-parent `git merge`:
  it builds a new commit as a direct child of the central revision recorded
  in `repo/REPO/.gitrepo` - not of the current HEAD - and applies the
  subrepo's diff there, where it is guaranteed to apply cleanly regardless
  of what else happened on central's actual HEAD since. That commit (the
  "import commit") also updates `.gitrepo` to record the new sync point.
  Merging it into the active branch is then an ordinary `git merge`: if
  there is a real conflict, git surfaces it exactly as it always does, for
  a human to resolve.

## Applying directly

A fake `central` and a fake `widget`, as usual - someone pushes directly to
`widget`'s `subrepo` branch (standing in for something fetched from its
real remote), while central hasn't touched `repo/widget/` since the last
sync. So `import` applies the upstream change straight onto HEAD, no merge
needed: *)

let%expect_test "direct import (central has no local changes)" =
  let vcs = Volgo_git_unix.create () in
  let widget = Central.Subrepo.v "widget" in
  let fake_central = Central_test_helpers.create ~vcs ~subrepos:[ widget ] in
  let { Central_test_helpers.Fake_central.central_root; _ } = fake_central in
  let fake_widget =
    Central_test_helpers.Fake_central.find_exn fake_central ~subrepo:widget
  in
  (* Someone pushes directly to the [subrepo] branch, bypassing central. *)
  let readme = Vcs.Path_in_repo.v "README.md" in
  Vcs.git
    vcs
    ~repo_root:fake_widget.repo_root
    ~args:[ "checkout"; "subrepo" ]
    ~f:Vcs.Git.exit0;
  Central_test_helpers.append_file
    ~repo_root:fake_widget.repo_root
    ~path_in_repo:readme
    ~text:"\nEdited directly upstream.\n";
  Vcs.add vcs ~repo_root:fake_widget.repo_root ~path:readme;
  let (_ : Vcs.Rev.t) =
    Central_test_helpers.commit
      ~vcs
      ~repo_root:fake_widget.repo_root
      ~commit_message:"Edited directly upstream"
  in
  let harness = Central_test_harness.create ~repo_root:central_root in
  let@ central = Central_test_harness.with_cli harness ~cwd:central_root in
  central [ [ "import"; "widget" ] ];
  (* @mdexp.snapshot *)
  [%expect
    {|
    $ central import widget
    [ OK ] Imported into [main] directly (no merge needed).
    |}];
  (* @mdexp

     A single, linear commit lands directly on top of HEAD - no second
     parent, no merge commit. `-m` was left out here, so the message falls
     back to `"Import changes from widget"`: *)
  Central_test_helpers.print_log_subjects ~vcs ~repo_root:central_root ~ref_:"main" ();
  (* @mdexp.snapshot *)
  [%expect
    {|
    Import changes from widget
    Add fake subrepo widget
    Initial commit
    |}];
  Central_test_helpers.print_file
    ~repo_root:central_root
    ~path_in_repo:(Vcs.Path_in_repo.v "repo/widget/README.md");
  (* @mdexp.snapshot { lang: "markdown" } *)
  [%expect
    {|
    # widget

    This is a fake [widget] repo, generated by [Central_test_helpers] for tests.

    Edited directly upstream.
    |}]
;;

