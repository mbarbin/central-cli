## Falling back to a merge

This time, central *does* touch something under `repo/widget/` since the
last sync - a new file of its own, `NOTES.md`, unrelated to the file
upstream changed. `import` can no longer assume `repo/widget/` is
untouched, so it falls back to building an import commit as a child of the
last sync point and merging it in. Since the two sides touch different
files, the merge still completes cleanly on its own: *)

let%expect_test "import with merge (central has local changes too)" =
  let vcs = Volgo_git_unix.create () in
  let widget = Central.Subrepo.v "widget" in
  let fake_central = Central_test_helpers.create ~vcs ~subrepos:[ widget ] in
  let { Central_test_helpers.Fake_central.central_root; _ } = fake_central in
  let fake_widget =
    Central_test_helpers.Fake_central.find_exn fake_central ~subrepo:widget
  in
  (* Someone pushes directly to the [subrepo] branch, bypassing central. *)
  let subrepo_readme = Vcs.Path_in_repo.v "README.md" in
  Vcs.git
    vcs
    ~repo_root:fake_widget.repo_root
    ~args:[ "checkout"; "subrepo" ]
    ~f:Vcs.Git.exit0;
  Central_test_helpers.append_file
    ~repo_root:fake_widget.repo_root
    ~path_in_repo:subrepo_readme
    ~text:"\nEdited directly upstream.\n";
  Vcs.add vcs ~repo_root:fake_widget.repo_root ~path:subrepo_readme;
  let (_ : Vcs.Rev.t) =
    Central_test_helpers.commit
      ~vcs
      ~repo_root:fake_widget.repo_root
      ~commit_message:"Edited directly upstream"
  in
  (* Meanwhile, central also gets its own, unrelated change under
     [repo/widget/] - a new file, so it cannot conflict textually with the
     incoming change, but it does mean central has changes of its own since
     the last sync, forcing the merge path. *)
  let notes_path = Vcs.Path_in_repo.v "repo/widget/NOTES.md" in
  Central_test_helpers.write_file
    ~repo_root:central_root
    ~path_in_repo:notes_path
    ~contents:"Some local notes.\n";
  Vcs.add vcs ~repo_root:central_root ~path:notes_path;
  let (_ : Vcs.Rev.t) =
    Central_test_helpers.commit
      ~vcs
      ~repo_root:central_root
      ~commit_message:"Add local notes under widget"
  in
  let harness = Central_test_harness.create ~repo_root:central_root in
  let@ central = Central_test_harness.with_cli harness ~cwd:central_root in
  central [ [ "import"; "widget" ] ];
  (* @mdexp.snapshot *)
  [%expect
    {|
    $ central import widget
    [ OK ] Built the import commit.
    Merge made by the 'ort' strategy.
     repo/widget/.gitrepo  | 4 ++--
     repo/widget/README.md | 2 ++
     2 files changed, 4 insertions(+), 2 deletions(-)
    [ OK ] Imported into [main].
    |}];
  (* @mdexp

     Unlike the direct case above, the import commit sits as a child of the
     *old* sync point, not of central's HEAD at the time - a separate line
     of history, joined by the merge: *)
  Central_test_helpers.print_log_subjects
    ~vcs
    ~repo_root:central_root
    ~ref_:"main"
    ~first_parent:true
    ();
  (* @mdexp.snapshot *)
  [%expect
    {|
    Merge widget import
    Add local notes under widget
    Add fake subrepo widget
    Initial commit
    |}]
;;

